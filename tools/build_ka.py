#!/usr/bin/env python3
"""Build the Georgian site (ka/) from the English pages.

Edit index.html / projects.html in English, add any new strings to i18n/ka.json,
then run:  python3 tools/build_ka.py
Strings with no translation are listed and left in English, so nothing breaks.
"""
import html, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGES = ['index.html', 'projects.html']
FONT = ('<link href="https://fonts.googleapis.com/css2?family=Noto+Sans+Georgian:wght@400;500;700;800&display=swap" rel="stylesheet">\n'
        '<style>body, button { font-family: "Schibsted Grotesk", "Noto Sans Georgian", system-ui, sans-serif; }</style>')
TOKEN = re.compile(r'(<!--.*?-->|<script\b.*?</script>|<style\b.*?</style>|<[^>]+>)', re.S)
ATTR = re.compile(r'(\b(?:alt|aria-label|title|content)=")([^"]*)(")')
PATH = re.compile(r'(\b(?:src|href|poster|data-video|data-poster)=")((?:img|video)/|style\.css|partners\.js)')


def main():
    d = json.load(open(os.path.join(ROOT, 'i18n', 'ka.json'), encoding='utf-8'))
    strings, keep, raw = d['strings'], set(d['keep']), d['raw']
    missing = []

    def tr(text):
        key = ' '.join(html.unescape(text).split())
        if key in strings:
            return html.escape(strings[key], quote=False)
        if key and key not in keep and re.search(r'[A-Za-z]{2}', key):
            missing.append(key)
        return None

    def tr_attr(m):
        t = tr(m.group(2))
        return m.group(1) + (t.replace('"', '&quot;') if t is not None else m.group(2)) + m.group(3)

    os.makedirs(os.path.join(ROOT, 'ka'), exist_ok=True)
    for page in PAGES:
        s = open(os.path.join(ROOT, page), encoding='utf-8').read()
        for a, b in raw.items():
            s = s.replace(a, b)
        out = []
        for tok in TOKEN.split(s):
            if not tok:
                continue
            if tok.startswith('<style'):
                out.append(tok.replace('url("img/', 'url("../img/'))
            elif tok.startswith('<script'):
                out.append(PATH.sub(r'\1../\2', tok))
            elif tok.startswith('<!--'):
                out.append(tok)
            elif tok.startswith('<'):
                if not tok.startswith(('<link', '<meta name="viewport"', '<meta charset')):
                    tok = ATTR.sub(tr_attr, tok)
                out.append(PATH.sub(r'\1../\2', tok))
            else:
                m = re.match(r'(\s*)(.*?)(\s*)$', tok, re.S)
                t = tr(m.group(2)) if m.group(2).strip() else None
                out.append(m.group(1) + t + m.group(3) if t is not None else tok)
        s = ''.join(out)
        s = s.replace('<html lang="en">', '<html lang="ka">', 1)
        s = s.replace('content="https://tskdev.org/"', 'content="https://tskdev.org/ka/"')
        s = s.replace('content="https://tskdev.org/projects.html"', 'content="https://tskdev.org/ka/projects.html"')
        s = s.replace('<link rel="stylesheet" href="../style.css">', '<link rel="stylesheet" href="../style.css">\n' + FONT, 1)
        s = s.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- Generated by tools/build_ka.py from ../' + page + '. Do not edit by hand. -->', 1)
        open(os.path.join(ROOT, 'ka', page), 'w', encoding='utf-8').write(s)

    if missing:
        print('Untranslated (left in English):')
        for m in dict.fromkeys(missing):
            print('  ', m)
    print('built ka/' + ', ka/'.join(PAGES))


if __name__ == '__main__':
    sys.exit(main())
